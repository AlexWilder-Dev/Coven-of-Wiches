// One-off: turn the OpenStreetMap extract in research/market-row-osm.json into SVG geometry
// for the Market Row map. Output is plain metres, north up, centred near the T-junction.
import { readFile, writeFile } from 'node:fs/promises';

const osm = JSON.parse(await readFile('research/market-row-osm.json', 'utf8'));
const LAT0 = 51.462;
const LON0 = -0.1132;
const KX = 111320 * Math.cos((LAT0 * Math.PI) / 180);
const KY = 111320;

const P = ([lat, lon]) => [+((lon - LON0) * KX).toFixed(1), +(-(lat - LAT0) * KY).toFixed(1)];
const line = (pts) => pts.map((p, i) => `${i ? 'L' : 'M'}${P(p).join(' ')}`).join('');
const poly = (pts) => line(pts) + 'Z';
const way = (k) => osm.ways[k].pts;
const dist = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1]);
const len = (pts) => pts.slice(1).reduce((s, p, i) => s + dist(P(pts[i]), P(p)), 0);
const centre = (pts) => [pts.reduce((s, p) => s + p[0], 0) / pts.length, pts.reduce((s, p) => s + p[1], 0) / pts.length];

// Passages: west runs Electric Lane -> junction -> Coldharbour Lane, east runs Atlantic Road -> junction
const west = way('passage_west');
const east = way('passage_east');
const junction = west[2];
const coldharbourEntrance = west[3];

// 14D's frontage: the 14D unit centre projected onto the Coldharbour arm
const c14 = centre(way('unit_14d'));
const [jx, jy] = P(junction);
const [cx, cy] = P(coldharbourEntrance);
const [ux, uy] = P(c14);
const t = ((ux - jx) * (cx - jx) + (uy - jy) * (cy - jy)) / ((cx - jx) ** 2 + (cy - jy) ** 2);
const front = [+(jx + t * (cx - jx)).toFixed(1), +(jy + t * (cy - jy)).toFixed(1)];
const toLL = ([x, y]) => [LAT0 - y / KY, LON0 + x / KX];
const frontLL = toLL(front);

const routes = [
  { from: 'electric', label: 'Electric Lane', pts: [west[0], west[1], junction, frontLL] },
  { from: 'atlantic', label: 'Atlantic Road', pts: [...east, frontLL] },
  { from: 'coldharbour', label: 'Coldharbour Lane', pts: [coldharbourEntrance, frontLL] },
].map((r) => ({ from: r.from, label: r.label, d: line(r.pts), metres: Math.round(len(r.pts)), start: P(r.pts[0]) }));

const streets = [
  { name: 'Coldharbour Lane', keys: ['coldharbour_1', 'coldharbour_2'] },
  { name: 'Electric Lane', keys: ['electric_lane_1', 'electric_lane_2', 'electric_lane_3'] },
  { name: 'Atlantic Road', keys: ['atlantic_1', 'atlantic_2', 'atlantic_3', 'atlantic_4', 'atlantic_5', 'atlantic_6', 'atlantic_7'] },
  { name: 'Electric Avenue', keys: ['electric_avenue'] },
].map((s) => ({ name: s.name, d: s.keys.map((k) => line(way(k))).join('') }));

const out = `// Generated by scripts/build-map.mjs from research/market-row-osm.json.
// Map data (c) OpenStreetMap contributors (ODbL). Units are metres, north up.
export const VIEWBOX = { x: -78, y: -46, w: 150, h: 96 };

export const MARKET_ROW = ${JSON.stringify(poly(way('market_row')))};
export const PASSAGES = ${JSON.stringify([line(west), line(east)])};
export const UNIT_14D = ${JSON.stringify(poly(way('unit_14d')))};
export const UNIT_14D_CENTRE = ${JSON.stringify(P(c14))} as const;
export const ESMES = ${JSON.stringify(poly(way('unit_16a_esmes')))};
export const ESMES_CENTRE = ${JSON.stringify(P(centre(way('unit_16a_esmes'))))} as const;
export const FRONT = ${JSON.stringify(front)} as const;

export const STREETS = ${JSON.stringify(streets, null, 2)};

export const ROUTES = ${JSON.stringify(routes, null, 2)} as const;
`;

await writeFile('src/components/find/geometry.ts', out);
